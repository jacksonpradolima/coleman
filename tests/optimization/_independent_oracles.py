"""Small exact test oracles independent from the production dual solver.

The face oracle enumerates at most five labels per coordinate, for at most four
coordinates. It is deliberately unsuitable as a production optimizer. Its
certificate uses feasible exchange directions rather than the production
soft-threshold map or its breakpoint implementation.
"""

from dataclasses import dataclass
from fractions import Fraction
from itertools import product

Vector = tuple[Fraction, ...]


@dataclass(frozen=True)
class FaceMinimum:
    """Retain one exact primal minimum and its possible multiplier interval."""

    weights: Vector
    objective: Fraction
    dual_lower: Fraction | None
    dual_upper: Fraction | None


def full_movement(weights: Vector, old: Vector) -> Fraction:
    """Return full coefficient L1 variation, never paid or executed-book cost."""
    return sum((abs(value - previous) for value, previous in zip(weights, old, strict=True)), Fraction())


def objective(weights: Vector, proposal: Vector, old: Vector, strength: Fraction) -> Fraction:
    """Evaluate the half-squared proximity plus full-L1 objective exactly."""
    squared = sum(((value - target) ** 2 for value, target in zip(weights, proposal, strict=True)), Fraction())
    return squared / 2 + strength * full_movement(weights, old)


def effective_intervals(
    lower: Vector,
    upper: Vector,
    old: Vector,
    *,
    allowances: Vector | None = None,
    period_origin: Vector | None = None,
    used: Vector | None = None,
) -> tuple[Vector, Vector]:
    """Derive raw exact boxes without reading production interval evidence.

    Without ``period_origin`` the allowance is per release. With a period origin
    and no ``used`` it bounds net displacement. With ``used`` it bounds remaining
    accumulated absolute variation, centered on the last actual emission.
    Negative remaining allowances intentionally yield reversed intervals.
    """
    if allowances is None:
        if period_origin is not None or used is not None:
            raise ValueError("A movement oracle requires declared allowances")
        return lower, upper
    center = old if period_origin is None or used is not None else period_origin
    remaining = allowances if used is None else tuple(a - u for a, u in zip(allowances, used, strict=True))
    return (
        tuple(max(lo, value - radius) for lo, value, radius in zip(lower, center, remaining, strict=True)),
        tuple(min(hi, value + radius) for hi, value, radius in zip(upper, center, remaining, strict=True)),
    )


def _derivatives(value: Fraction, proposal: Fraction, old: Fraction, strength: Fraction) -> tuple[Fraction, Fraction]:
    """Return exact left and right scalar objective derivatives."""
    left = value - proposal + (strength if value > old else -strength)
    right = value - proposal + (-strength if value < old else strength)
    return left, right


def exchange_certificate(
    weights: Vector, proposal: Vector, old: Vector, lower: Vector, upper: Vector, strength: Fraction
):
    """Certify optimality by every permitted infinitesimal coordinate transfer.

    At a feasible point the tangent cone of a box/simplex intersection is
    generated by transfers from coordinates above their lower bound to distinct
    coordinates below their upper bound. Their directional derivatives must all
    be nonnegative. Convexity makes this sufficient; the positive quadratic
    term makes the feasible primal optimum unique. No dual root is evaluated.
    """
    if sum(weights, Fraction()) != 1 or any(
        value < lo or value > hi for value, lo, hi in zip(weights, lower, upper, strict=True)
    ):
        return False
    derivatives = tuple(
        _derivatives(p, r, before, strength) for p, r, before in zip(weights, proposal, old, strict=True)
    )
    for receiver, (value, hi) in enumerate(zip(weights, upper, strict=True)):
        if value == hi:
            continue
        for donor, (other, lo) in enumerate(zip(weights, lower, strict=True)):
            if receiver != donor and other > lo and derivatives[receiver][1] < derivatives[donor][0]:
                return False
    return True


def _dual_interval(weights: Vector, proposal: Vector, old: Vector, lower: Vector, upper: Vector, strength: Fraction):
    """Recover the multiplier interval only after independent primal checking."""
    lows, highs = [], []
    for p, r, before, lo, hi in zip(weights, proposal, old, lower, upper, strict=True):
        left, right = _derivatives(p, r, before, strength)
        if p < hi:
            lows.append(-right)
        if p > lo:
            highs.append(-left)
    return max(lows) if lows else None, min(highs) if highs else None


def face_minimum(proposal: Vector, old: Vector, lower: Vector, upper: Vector, strength: Fraction) -> FaceMinimum | None:
    """Enumerate exact faces; return None only for an empty box/simplex set.

    Labels are lower, upper, held, below-old and above-old. Free coordinates on
    a selected smooth face satisfy ``p_i = r_i - sign_i * strength - nu``.
    Solving their one affine sum constraint is independent from sorted dual
    breakpoints or numerical root search. All candidates also pass the separate
    feasible-exchange certificate. At most 5**4 labels are examined.
    """
    if not 1 <= len(proposal) <= 4 or len({len(proposal), len(old), len(lower), len(upper)}) != 1:
        raise ValueError("The independent face oracle supports one through four complete coordinates")
    if strength < 0:
        raise ValueError("A convex movement strength must be nonnegative")
    if (
        any(lo > hi for lo, hi in zip(lower, upper, strict=True))
        or sum(lower, Fraction()) > 1
        or sum(upper, Fraction()) < 1
    ):
        return None
    minima: dict[Vector, FaceMinimum] = {}
    for labels in product(range(5), repeat=len(proposal)):
        fixed = [lower[i] if label == 0 else upper[i] if label == 1 else old[i] for i, label in enumerate(labels)]
        free = tuple(i for i, label in enumerate(labels) if label >= 3)
        if free:
            total = sum((fixed[i] for i, label in enumerate(labels) if label < 3), Fraction())
            total += sum((proposal[i] + (strength if labels[i] == 3 else -strength) for i in free), Fraction())
            nu = (total - 1) / len(free)
            for i in free:
                fixed[i] = proposal[i] + (strength if labels[i] == 3 else -strength) - nu
        candidate = tuple(fixed)
        if any(
            (label == 3 and candidate[i] > old[i]) or (label == 4 and candidate[i] < old[i])
            for i, label in enumerate(labels)
        ):
            continue
        if not exchange_certificate(candidate, proposal, old, lower, upper, strength):
            continue
        lo, hi = _dual_interval(candidate, proposal, old, lower, upper, strength)
        minima[candidate] = FaceMinimum(candidate, objective(candidate, proposal, old, strength), lo, hi)
    if len(minima) != 1:
        raise AssertionError(f"A nonempty strongly convex oracle problem produced {len(minima)} distinct optima")
    return next(iter(minima.values()))
